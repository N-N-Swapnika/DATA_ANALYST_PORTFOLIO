-- CASE STUDY : SWAPCART CUSTOMER ANALYSIS

-- SWAPCART IS AN E-COMMERCE COMPANY.
-- ITS MANAGEMENT WANTS TO UNDERSTAND CUSTOMER SPENDING PATTERNS ACROSS DIFFERENT CITIES.

-- ASKED TO ANALYSE THE CUSTOMER DATABASE AND PREPARE A REPORT.

USE SWAPCART;

-- PART A : BASIC CUSTOMER ANALYSIS

-- 1. CUSTOMER DETAILS:
-- DISPLAY ALL CUSTOMER NAMES, CITIES AND TOTAL SPENDING.
SELECT CUSTOMER_NAME, CITY, TOTAL_SPENT
FROM CUSTOMER;

-- 2. HIGH-SPENDING CUSTOMERS:
-- FIND CUSTOMERS WHOSE TOTAL SPENDING IS GREATER THAN 40000.
SELECT CUSTOMER_NAME, TOTAL_SPENT
FROM CUSTOMER 
WHERE TOTAL_SPENT > 40000;

-- 3. CUSTOMER FILTERING:
-- FIND FEMALE CUSTOMERS WHO ARE OLDER THAN 24 YEARS.
SELECT CUSTOMER_NAME, AGE
FROM CUSTOMER
WHERE GENDER = 'FEMALE'
AND AGE > 24;

-- 4. TOP CUSTOMERS
-- DISPLAY TOP 3 HIGHEST-SPENDING CUSTOMERS, SHOWING THEIR NAMES AND SPENDING AMOUNTS.
SELECT CUSTOMER_NAME, TOTAL_SPENT
FROM CUSTOMER
ORDER BY TOTAL_SPENT DESC
LIMIT 3;

-- 5. CUSTOMER STATISTICS
-- TOTAL NUMBER OF CUSTOMERS, TOTAL CUSTOMER SPENDING, AVERAGE CUSTOMER SPENDING, HIGHEST SPENDING AND LOWEST SPENDING.
SELECT COUNT(*) AS TOTAL_CUSTOMERS, SUM(TOTAL_SPENT) AS TOTAL_SPENDING, AVG(TOTAL_SPENT) AS AVERAGE_SPENDING,
MAX(TOTAL_SPENT) AS HIGHEST_SPENDING, MIN(TOTAL_SPENT) AS LOWEST_SPENDING
FROM CUSTOMER;

-- PART B : GROUP BY AND HAVING

-- 6. CITY-WISE CUSTOMER COUNT
-- FIND THE NUMBER OF CUSTOMERS IN EACH CITY
SELECT CITY, COUNT(*) AS TOTAL_CUSTOMERS
FROM CUSTOMER
GROUP BY CITY;

-- 7. CITY-WISE REVENUE
-- CALCULATE THE TOTAL SPENDING OF CUSTOMERS IN EACH CITY. DISPLAY THE HIGHEST REVENUE CITY FIRST.
SELECT CITY, COUNT(*) AS TOTAL_CUSTOMERS, SUM(TOTAL_SPENT) AS TOTAL_REVENUE
FROM CUSTOMER
GROUP BY CITY
ORDER BY TOTAL_REVENUE DESC;

-- 8. REVENUE FILTERING
-- FIND CITIES WHOSE TOTAL CUSTOMER SPENDING IS GREATER THAN 50000.
SELECT CITY, COUNT(*) AS TOTAL_CUSTOMERS, SUM(TOTAL_SPENT) AS TOTAL_REVENUE
FROM CUSTOMER
GROUP BY CITY
HAVING TOTAL_REVENUE > 50000;

-- 9. COMBINED BUSINESS CONDITIONS
-- MANAGEMENT WANTS TO IDENTIFY CITIES WHERE CUSTOMERS OLDER THAN 25 HAVE COMBINED SPENDING GREATER THAN 50000.
SELECT CITY, COUNT(*) AS QUALIFYING_CUSTOMERS, SUM(TOTAL_SPENT) AS COMBINED_SPENDING 
FROM CUSTOMER 
WHERE AGE > 25
GROUP BY CITY
HAVING COMBINED_SPENDING > 50000;

-- PART C : CASE EXPRESSIONS

-- 10. CUSTOMER SEGMENTATION
-- CLASSIFY CUSTOMERS ACCORDING TO THEIR SPENDING
-- BELOW 20000 AS LOW, 20000 TO 50000 AS MEDIUM, ABOVE 50000 AS HIGH
SELECT CUSTOMER_NAME, TOTAL_SPENT,
CASE
WHEN TOTAL_SPENT < 20000 THEN 'LOW'
WHEN TOTAL_SPENT BETWEEN 20000 AND 50000 THEN 'MEDIUM'
ELSE 'HIGH'
END AS SPENDING_CATEGORY
FROM CUSTOMER;

-- 11. CUSTOMER CATEGORY SUMMARY
-- USING THE SAME CATEGORY FROM THE ABOVE PROBLEM, CALCULATE HOW MANY CUSTOMERS BELONG TO EACH CATEGORY
SELECT COUNT(*) AS TOTAL_CUSTOMERS, SUM(TOTAL_SPENT) AS CATEGORY_TOTAL,
CASE
WHEN TOTAL_SPENT < 20000 THEN 'LOW'
WHEN TOTAL_SPENT BETWEEN 20000 AND 50000 THEN 'MEDIUM'
ELSE 'HIGH'
END AS SPENDING_CATEGORY
FROM CUSTOMER
GROUP BY SPENDING_CATEGORY;

-- PART D : MANAGEMENT CHALLENGE

-- 12. CITY PERFORMANCE REPORT
-- MANAGEMENT WANTS A REPORT CONTAINING: CITY, TOTAL NO.OF CUSTOMERS, TOTAL REVENUE, AVERAGE SPENDING, HIGHEST CUSTOMER SPENDING.
-- SORT THE CITIES FROM HIGHEST TO LOWEST.
SELECT CITY, COUNT(*) AS TOTAL_CUSTOMERS, SUM(TOTAL_SPENT) AS TOTAL_REVENUE, AVG(TOTAL_SPENT) AS AVERAGE_SPENDING, MAX(TOTAL_SPENT) AS HIGHEST_SPENDING
FROM CUSTOMER
GROUP BY CITY
ORDER BY TOTAL_REVENUE DESC;

-- 13. BUSINESS PERFORMANCE CLASSIFICATION
-- CLASSIFY EACH CITY BASED ON ITS TOTAL REVENUE
-- ABOVE 100000 AS HIGH, 50000 TO 100000 AS MEDIUM, BELOW 50000 AS LOW
-- DISPLAY CITY, REVENUE AND PERFORMANCE CATEGORY
SELECT CITY, SUM(TOTAL_SPENT) AS REVENUE,
CASE
WHEN SUM(TOTAL_SPENT) > 100000 THEN 'HIGH'
WHEN SUM(TOTAL_SPENT) BETWEEN 50000 AND 100000 THEN 'MEDIUM'
ELSE 'LOW'
END AS PERFORMANCE
FROM CUSTOMER
GROUP BY CITY;

-- 14. MARKETING TARGET
-- THE MARKETING TEAM WANTS TO IDENTIFY CITIES THAT: HAVE ATLEAST 2 CUSTOMERS, HAVE AVERAGE CUSTOMER SPENDING GREATER THAN 30000
SELECT CITY, COUNT(*) AS TOTAL_CUSTOMERS, AVG(TOTAL_SPENT) AS AVERAGE_SPENDING
FROM CUSTOMER 
GROUP BY CITY
HAVING COUNT(*) >= 2
AND AVG(TOTAL_SPENT) > 30000
ORDER BY AVERAGE_SPENDING DESC;
